#!/usr/bin/env bash
# Runs one Unit 6 formal Benchmark measured run: preflight, fresh
# mock-llm+gateway, warm-up (discarded), measurement (kept), drain, collect.
# See docs/test-results/phase1/unit6-benchmark-plan.md.
#
# Usage: ./scripts/run-formal-benchmark.sh <label> <core> <max> <queueCap> <rejection> \
#          <load_label> <rate> <warmup_sec> <measurement_sec> <run_number> [preAllocatedVUs]
set -euo pipefail

LABEL="$1"; CORE="$2"; MAX="$3"; QUEUE_CAP="$4"; REJECTION="$5"
LOAD_LABEL="$6"; RATE="$7"; WARMUP_SEC="$8"; MEASUREMENT_SEC="$9"; RUN_NUMBER="${10}"
# Config A's wide iteration-duration variance (near-instant vs near-deadline)
# was found to make k6's constant-arrival-rate scheduler drop ~2.5-2.8% of
# iterations with the default PRE_ALLOCATED_VUS=100 even though vus_max never
# approached MAX_VUS=1000 — i.e. it wasn't a ceiling problem, it was
# on-demand VU spin-up latency. Pre-allocating enough VUs upfront (confirmed
# empirically: 800 -> 0 dropped_iterations at rate=12) removes that entirely.
# See docs/test-results/phase1/unit6-formal-benchmark-results.md section on
# dropped_iterations.
PRE_ALLOCATED_VUS="${11:-100}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUN_ID="${LABEL}-${LOAD_LABEL}-run${RUN_NUMBER}"
OUT_DIR="${ROOT}/docs/test-results/phase1/unit6/${RUN_ID}"
mkdir -p "${OUT_DIR}"

cd "${ROOT}"
echo "=== [${RUN_ID}] $(date -u +%Y-%m-%dT%H:%M:%SZ) starting ==="

# ---- Preflight ----
UNRELATED=$(docker ps --format '{{.Names}}' | grep -v '^llm-concurrency-lab-' || true)
if [ -n "${UNRELATED}" ]; then
  echo "[${RUN_ID}] FATAL: unrelated container(s) running, aborting matrix: ${UNRELATED}" >&2
  exit 1
fi

HOST_ARCH=$(uname -m)
CONTAINER_ARCH=$(docker run --rm alpine uname -m)
# macOS reports "arm64", Linux containers report "aarch64" for the same
# architecture — normalize both before comparing (not a real mismatch).
norm_arch() { case "$1" in arm64|aarch64) echo "arm64" ;; *) echo "$1" ;; esac; }
if [ "$(norm_arch "${HOST_ARCH}")" != "$(norm_arch "${CONTAINER_ARCH}")" ]; then
  echo "[${RUN_ID}] FATAL: arch mismatch host=${HOST_ARCH} container=${CONTAINER_ARCH}" >&2
  exit 1
fi

vm_epoch() { docker run --rm alpine date +%s; }

HOST_EPOCH=$(date +%s)
CONTAINER_EPOCH=$(vm_epoch)
DRIFT=$(( HOST_EPOCH > CONTAINER_EPOCH ? HOST_EPOCH - CONTAINER_EPOCH : CONTAINER_EPOCH - HOST_EPOCH ))
if [ "${DRIFT}" -gt 5 ]; then
  echo "[${RUN_ID}] FATAL: host/container clock drift ${DRIFT}s" >&2
  exit 1
fi

cat > docker-compose.override.yml <<EOF
# Auto-generated by scripts/run-formal-benchmark.sh for run ${RUN_ID} — do not edit by hand.
services:
  gateway:
    environment:
      MOCK_LLM_BASE_URL: http://mock-llm:8000
      CHAT_CORE_POOL_SIZE: "${CORE}"
      CHAT_MAX_POOL_SIZE: "${MAX}"
      CHAT_QUEUE_CAPACITY: "${QUEUE_CAP}"
      CHAT_REJECTION_POLICY: ${REJECTION}
      CHAT_CONNECT_TIMEOUT_MS: "3000"
      CHAT_READ_TIMEOUT_MS: "30000"
      CHAT_TOTAL_TIMEOUT_MS: "60000"
EOF

# --renew-anon-volumes (-V): plain --force-recreate replaces the CONTAINER
# but, by Compose's own default, still reattaches the OLD container's
# anonymous volumes (prom/prometheus declares one for /prometheus) — so
# without -V, Prometheus's TSDB (and therefore every metric value) silently
# survives "recreation". Root-caused via direct reproduction: switching
# executor config left the previous config's stale gateway_request_outcome_total
# values being served by Prometheus for minutes after the new (empty) gateway
# came up, because Prometheus never received a fresh sample for a label that
# the new config doesn't exercise (e.g. "rejected") and just kept serving the
# last (correct-at-the-time, but now stale) one — see
# docs/test-results/phase1/unit6-benchmark-plan.md section 9.
docker compose up -d --force-recreate --renew-anon-volumes mock-llm gateway prometheus >/dev/null

GW_HEALTH=starting; ML_HEALTH=starting
for i in $(seq 1 30); do
  GW_HEALTH=$(docker inspect --format='{{.State.Health.Status}}' llm-concurrency-lab-gateway-1 2>/dev/null || echo "starting")
  ML_HEALTH=$(docker inspect --format='{{.State.Health.Status}}' llm-concurrency-lab-mock-llm-1 2>/dev/null || echo "starting")
  [ "${GW_HEALTH}" = "healthy" ] && [ "${ML_HEALTH}" = "healthy" ] && break
  sleep 1
done
if [ "${GW_HEALTH}" != "healthy" ] || [ "${ML_HEALTH}" != "healthy" ]; then
  echo "[${RUN_ID}] FATAL: containers not healthy (gateway=${GW_HEALTH} mock-llm=${ML_HEALTH})" >&2
  exit 1
fi

sleep 6  # let prometheus scrape at least once before we trust "up"
PROM_UP_GW=$(curl -s --data-urlencode 'query=up{job="gateway-mvc-executor-java8"}' http://localhost:9091/api/v1/query | python3 -c "import json,sys;d=json.load(sys.stdin);r=d['data']['result'];print(r[0]['value'][1] if r else '0')")
PROM_UP_ML=$(curl -s --data-urlencode 'query=up{job="mock-llm-fastapi"}' http://localhost:9091/api/v1/query | python3 -c "import json,sys;d=json.load(sys.stdin);r=d['data']['result'];print(r[0]['value'][1] if r else '0')")
if [ "${PROM_UP_GW}" != "1" ] || [ "${PROM_UP_ML}" != "1" ]; then
  echo "[${RUN_ID}] FATAL: prometheus not scraping targets (gw=${PROM_UP_GW} mock=${PROM_UP_ML})" >&2
  exit 1
fi

ASYNC_ACTIVE=$(curl -s http://localhost:8080/metrics | awk '/^gateway_async_active_requests /{print $2}')
QUEUE_SIZE=$(curl -s http://localhost:8080/metrics | awk '/^gateway_executor_queue_size /{print $2}')
if [ "${ASYNC_ACTIVE}" != "0.0" ] || [ "${QUEUE_SIZE}" != "0.0" ]; then
  echo "[${RUN_ID}] FATAL: not idle before start (async_active=${ASYNC_ACTIVE} queue=${QUEUE_SIZE})" >&2
  exit 1
fi

echo "[${RUN_ID}] preflight OK (drift=${DRIFT}s arch=${HOST_ARCH})"

NET=$(docker network ls --format '{{.Name}}' | grep llm-lab)
# All measurement timestamps below are captured from the Docker VM's own
# clock (vm_epoch), NOT the host's — Prometheus lives in that same VM, so
# querying it with host-clock timestamps is only correct if host/VM drift is
# exactly 0 for the ENTIRE run, not just at the preflight instant. Root-caused
# after 2 of Unit 6's first 21 runs produced impossible negative-count deltas
# (a metric's value at "meas_start" reading HIGHER than at "meas_end" — e.g.
# stale-looking values from a different point in the VM's timeline than the
# host clock implied) — see docs/test-results/phase1/unit6-benchmark-plan.md.
START_TS=$(vm_epoch)

# ---- Warm-up (discarded) ----
WARMUP_START=$(vm_epoch)
docker run --rm --network "${NET}" \
  -v "${ROOT}/load-test-k6/scenarios:/scripts:ro" \
  -e GATEWAY_URL=http://gateway:8080/chat/stream \
  -e RATE="${RATE}" -e DURATION="${WARMUP_SEC}s" -e GRACEFUL_STOP=90s \
  -e PRE_ALLOCATED_VUS="${PRE_ALLOCATED_VUS}" -e MAX_VUS=1000 \
  -e K6_PROMETHEUS_RW_SERVER_URL=http://prometheus:9090/api/v1/write \
  --entrypoint k6 k6-sse:dev run -o experimental-prometheus-rw \
  /scripts/02-constant-arrival-rate.js > "${OUT_DIR}/warmup-k6.log" 2>&1 || echo "[${RUN_ID}] warm-up k6 exited non-zero (logged)"
WARMUP_END=$(vm_epoch)

echo "[${RUN_ID}] warm-up done, waiting for drain before measurement..."
for i in $(seq 1 120); do
  ACTIVE=$(curl -s -m 3 http://localhost:8080/metrics | awk '/^gateway_async_active_requests /{print $2}')
  [ "${ACTIVE}" = "0.0" ] && break
  sleep 1
done
# Real-time drain confirmation (direct curl to gateway) can land ahead of
# Prometheus's own next scrape (5s interval) — without this buffer, the
# measurement_start instant-query below can read a stale pre-drain sample
# for gateway_request_outcome_total specifically (outcome keeps changing
# until the last straggler completes, unlike received which stops changing
# once warm-up's arrival phase ends), inflating the windowed outcome delta
# with a few trailing warm-up completions. Confirmed empirically in a short
# validation run before committing to the full matrix.
sleep 8

# ---- Measurement (kept) ----
MEASUREMENT_START=$(vm_epoch)
docker run --rm --network "${NET}" \
  -v "${ROOT}/load-test-k6/scenarios:/scripts:ro" \
  -v "${OUT_DIR}:/results" \
  -e GATEWAY_URL=http://gateway:8080/chat/stream \
  -e RATE="${RATE}" -e DURATION="${MEASUREMENT_SEC}s" -e GRACEFUL_STOP=90s \
  -e PRE_ALLOCATED_VUS="${PRE_ALLOCATED_VUS}" -e MAX_VUS=1000 \
  -e K6_PROMETHEUS_RW_SERVER_URL=http://prometheus:9090/api/v1/write \
  -e "K6_PROMETHEUS_RW_TREND_STATS=p(50),p(95),p(99),min,max" \
  --entrypoint k6 k6-sse:dev run -o experimental-prometheus-rw \
  --summary-trend-stats "p(50),p(95),p(99),min,max" \
  --summary-export /results/k6-summary.json \
  /scripts/02-constant-arrival-rate.js > "${OUT_DIR}/measurement-k6.log" 2>&1 || echo "[${RUN_ID}] measurement k6 exited non-zero (logged)"

echo "[${RUN_ID}] measurement done, waiting for drain..."
for i in $(seq 1 120); do
  ACTIVE=$(curl -s -m 3 http://localhost:8080/metrics | awk '/^gateway_async_active_requests /{print $2}')
  [ "${ACTIVE}" = "0.0" ] && break
  sleep 1
done
sleep 8  # scrape buffer, see Unit 5 lesson (docs/decisions/request-outcome-accounting.md context)
MEASUREMENT_END=$(vm_epoch)
DRAIN_END=${MEASUREMENT_END}

# Post-run drift re-check (belt-and-suspenders on top of the vm_epoch fix
# above, and recorded in environment.json per the Unit 6 plan section 7).
POST_HOST_EPOCH=$(date +%s)
POST_CONTAINER_EPOCH=$(vm_epoch)
POST_DRIFT=$(( POST_HOST_EPOCH > POST_CONTAINER_EPOCH ? POST_HOST_EPOCH - POST_CONTAINER_EPOCH : POST_CONTAINER_EPOCH - POST_HOST_EPOCH ))
if [ "${POST_DRIFT}" -gt 5 ]; then
  echo "[${RUN_ID}] WARNING: host/VM clock drift grew to ${POST_DRIFT}s during this run (was ${DRIFT}s at preflight)" >&2
fi

cat > "${OUT_DIR}/timestamps.json" <<EOF
{
  "start_timestamp": ${START_TS},
  "warmup_start": ${WARMUP_START},
  "warmup_end": ${WARMUP_END},
  "measurement_start": ${MEASUREMENT_START},
  "measurement_end": ${MEASUREMENT_END},
  "drain_end": ${DRAIN_END}
}
EOF

cat > "${OUT_DIR}/environment.json" <<EOF
{
  "configuration": "${LABEL}",
  "load": "${LOAD_LABEL}",
  "run_number": ${RUN_NUMBER},
  "executor": {
    "core_pool_size": ${CORE}, "max_pool_size": ${MAX},
    "queue_capacity": ${QUEUE_CAP}, "rejection_policy": "${REJECTION}"
  },
  "arrival_rate_target": ${RATE},
  "k6_pre_allocated_vus": ${PRE_ALLOCATED_VUS},
  "warmup_duration_s": ${WARMUP_SEC},
  "measurement_duration_s": ${MEASUREMENT_SEC},
  "mock_llm_workload": {"first_chunk_delay_ms": 1000, "chunk_interval_ms": 200, "chunk_count": 20, "chunk_size_bytes": 64},
  "timeouts_ms": {"connect": 3000, "read": 30000, "total": 60000},
  "resource_limits": {"gateway": {"cpus": 1.0, "mem_limit": "1g"}, "mock_llm": {"cpus": 2.0, "mem_limit": "1g"}},
  "prometheus_scrape_interval_s": 5,
  "k6_image": "k6-sse:dev (k6 v1.8.0 + xk6-sse v0.1.11)",
  "log_level": "INFO",
  "jdk": "Eclipse Temurin 8", "spring_boot": "1.5.22.RELEASE",
  "preflight": {
    "host_arch": "${HOST_ARCH}", "container_arch": "${CONTAINER_ARCH}",
    "clock_drift_s": ${DRIFT}, "post_run_clock_drift_s": ${POST_DRIFT},
    "gateway_healthy": true, "mock_healthy": true,
    "prometheus_scrape_ok": true, "async_active_before": 0, "queue_size_before": 0,
    "unrelated_containers": [],
    "timestamp_clock_domain": "docker_vm (not host) — see scripts/run-formal-benchmark.sh vm_epoch()"
  }
}
EOF

docker logs llm-concurrency-lab-gateway-1 -t > "${OUT_DIR}/gateway.log" 2>&1 || true
docker logs llm-concurrency-lab-mock-llm-1 -t > "${OUT_DIR}/mock-llm.log" 2>&1 || true

python3 "${ROOT}/scripts/collect_formal_result.py" "${LABEL}" "${LOAD_LABEL}" "${RUN_NUMBER}" \
  "${MEASUREMENT_START}" "${MEASUREMENT_END}" "${RATE}" "${OUT_DIR}/k6-summary.json" http://localhost:9091 \
  | tee "${OUT_DIR}/result.json"

echo "=== [${RUN_ID}] $(date -u +%Y-%m-%dT%H:%M:%SZ) done ==="
